from pathlib import Path
import re
for name in ('soc_gpio','soc_timer','soc_i2c_master'):
    p=Path('rtl/peripherals')/(name+'.v');s=p.read_text(encoding='utf-8')
    s=re.sub(r'input  wire \[3:0\](\s+addr_i)',r'input  wire [11:0]\1',s)
    s=re.sub(r"4'h([0-9A-F])",lambda m: "12'h00"+m[1],s)
    p.write_text(s,encoding='utf-8')
p=Path('rtl/bus/soc_map.vh');s=p.read_text(encoding='utf-8')
s=s.replace('// Standard peripherals expose 16 bytes; QNN owns its complete 4 KiB page.','// Each MMIO slave owns 4 KiB; the slave rejects unimplemented 12-bit offsets.')
s=s.replace("`define SOC_MMIO_MASK   32'hFFFF_FFF0","`define SOC_MMIO_MASK   32'hFFFF_F000")
p.write_text(s,encoding='utf-8')
p=Path('rtl/bus/soc_bus.v');s=p.read_text(encoding='utf-8')
s=re.sub(r'\(slave_addr_o & `SOC_(?:MMIO|QNN)_MASK\) == (`SOC_\w+_BASE)',r'slave_addr_o[31:12] == (\1 >> 12)',s)
p.write_text(s,encoding='utf-8')
p=Path('rtl/soc/rv32_soc.v');s=p.read_text(encoding='utf-8')
s=s.replace('    parameter integer CLOCK_HZ = 50000000,','    parameter integer CLOCK_HZ = 50000000,\n    // Board dành LED[8:9] cho debug; phần mềm mặc định chỉ điều khiển 8 LED.\n    parameter integer GPIO_LED_WIDTH = 8,')
s=s.replace('output wire [9:0] leds_o','output wire [GPIO_LED_WIDTH-1:0] leds_o')
s=s.replace('    output wire       uart_tx_o,','    output wire       uart_tx_o,\n    // RX bất đồng bộ; uart_rx sở hữu synchronizer hai FF.\n    input wire uart_rx_i,')
s=s.replace('    soc_gpio u_gpio (','    soc_gpio #(.GPIO_LED_WIDTH(GPIO_LED_WIDTH)) u_gpio (')
s=s.replace('.addr_i(bus_addr[3:0])','.addr_i(bus_addr[11:0])')
s=s.replace('    soc_uart_tx #(\n','    soc_uart #(\n')
s=s.replace('        .tx_o(uart_tx_o),','        .tx_o(uart_tx_o),\n        .rx_i(uart_rx_i),')
s=s.replace('GPIO 10 bit','GPIO GPIO_LED_WIDTH bit')
s=s.replace('0000_000F','0000_0FFF').replace('2000_000F','2000_0FFF').replace('2000_100F','2000_1FFF').replace('2000_200F','2000_2FFF').replace('2000_400F','2000_4FFF')
s=s.replace('// Bus dữ liệu trả ready+err ngay cho địa chỉ không ánh xạ và ghi ROM.','// Bus dữ liệu chốt request/response; địa chỉ sai và ghi ROM kết thúc bằng fault.')
p.write_text(s,encoding='utf-8')
p=Path('rtl/board/de10_lite_top.v');s=p.read_text(encoding='utf-8')
s=s.replace('    output wire        UART_TX','    input wire UART_RX, // GPIO header [3], PIN_W9; 3.3-V UART RX.\n    output wire        UART_TX')
s=s.replace('wire [9:0] soc_leds','wire [7:0] soc_leds')
s=s.replace('    // 10 bit LED từ GPIO peripheral; board chỉ dùng [7:0] cho LED GPIO.','    // 8 bit LED phần mềm; LED[8:9] chỉ có nguồn debug riêng.')
s=s.replace('        .uart_tx_o(uart_tx),','        .uart_rx_i(UART_RX), .uart_tx_o(uart_tx),')
p.write_text(s,encoding='utf-8')
for p in Path('tb/peripherals').glob('*.v'):
    if 'uart' in p.name: continue # TX legacy vẫn có offset 4 bit bên trong wrapper.
    s=p.read_text(encoding='utf-8')
    s=re.sub(r'reg \[3:0\] addr\s*=\s*0, strb\s*=\s*(\d);',r'reg [11:0] addr=0;\n    reg [3:0] strb=\1;',s)
    s=s.replace('reg [3:0] addr;','reg [11:0] addr;')
    s=s.replace('input [3:0] register_address','input [11:0] register_address').replace('input [3:0] offset','input [11:0] offset')
    p.write_text(s,encoding='utf-8')
for p in Path('tb/soc').glob('*.v'):
    s=p.read_text(encoding='utf-8')
    s=s.replace('.uart_tx_o(', ".uart_rx_i(1'b1), .uart_tx_o(")
    s=s.replace('wire [9:0] leds','wire [7:0] leds').replace('input [9:0] expected_leds','input [7:0] expected_leds')
    s=s.replace("10'h300); // GPIO SB upper byte","8'h00); // GPIO SB outside 8-bit LED width is a no-op")
    s=s.replace("run_case(20'h20001, 12'h008", "run_case(20'h20001, 12'h010")
    p.write_text(s,encoding='utf-8')
p=Path('tb/bus/tb_rv32_soc_bus.v');s=p.read_text(encoding='utf-8').replace('(lane==5 || offset<16)?lane:-1','lane')
p.write_text(s,encoding='utf-8')
